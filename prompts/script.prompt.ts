/**
 * prompts/script.prompt.ts
 */
export function buildScriptPrompt(
  topic: string,
  angle: string,
  keyFacts: string[],
  hook: string
): string {
  return [
    `الموضوع: ${topic}`,
    `الزاوية السردية: ${angle}`,
    `الجملة الافتتاحية (استخدمها كما هي في المشهد الأول): ${hook}`,
    `حقائق ومعلومات للاستعانة بها: ${keyFacts.join(" | ")}`,
    "",
    "اكتب سيناريو فيديو عربي مقسّم إلى مشاهد (Scenes)، مش فقرة واحدة طويلة.",
    "أنت اللي تقرر عدد المشاهد ومدة كل مشهد حسب ثراء الموضوع نفسه --",
    "موضوع بسيط ممكن ياخد 6-8 مشاهد (حوالي دقيقة)، وموضوع غني بالتفاصيل ممكن ياخد",
    "20+ مشهد (حوالي 3-4 دقايق). لا يوجد طول ثابت مطلوب -- خليه مناسب للمحتوى.",
    "",
    "لكل مشهد: مدة تقديرية بالثواني تناسب طول النص المنطوق فيه (~2.5 كلمة/ثانية)،",
    "نص السرد الصوتي بالعربية الفصحى المبسطة، ووصف صورة/لقطة (Image Prompt) بالإنجليزية",
    "يصف المشهد بصريًا (يُستخدم لاحقًا في توليد صورة).",
    "",
    "أرجع الرد بصيغة JSON فقط بدون أي نص إضافي وبدون Markdown fences، بالشكل:",
    `{"scenes": [{"durationSec": 6, "narration": "...", "imagePrompt": "cinematic ..."}]}`,
  ].join("\n");
}
